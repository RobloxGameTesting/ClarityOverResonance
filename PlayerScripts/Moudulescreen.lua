	warn("SpecialMesh tidak ditemukan di dalam MeshTest.")
	return
end

local function startImageSequence(p, p2)
	local v2 = 1
	local count = #v
	local v3 = 1 / p
	local total = 0

	local RunService = game:GetService("RunService")
	RunService.RenderStepped:Connect(function(dt)
		total += dt

		local v4 = total

		if v3 + p2 <= v4 then
			Mesh.TextureId = "rbxassetid://" .. v[v2]

			v2 += 1

			if count < v2 then
				v2 = 1
			end

			total = 0
		end
	end)
end

