function StrobeBar192Segment.Update(p, buf, p2)
	local v8 = get_fixture_state(p)

	if not v8 then
		return
	end

	if p2 then
		v8.is_on = true

		local v9 = p.Address - 1

		local v10 = buffer.readu8(buf, v9) / 255
		local last_strobe_value = buffer.readu8(buf, v9 + 1)

		local last_red = buffer.readu8(buf, v9 + 2)
		local last_green = buffer.readu8(buf, v9 + 3)
		local last_blue = buffer.readu8(buf, v9 + 4)

		local v11 = buffer.readu8(buf, v9 + 5)
		local last_speed_value = buffer.readu8(buf, v9 + 7)

		if v10 <= 0 or count == 0 then
			set_off(v8) -- inferred equivalent call
		else
			local effect_index = v7[v11 + 1]
			local effect = config.effects[effect_index]

			local v12 = get_frames(effect)

			if #v12 == 0 then
				set_off(v8) -- inferred equivalent call
			else
				local active_mode = last_red > 0 or last_green > 0 or last_blue > 0

				if effect_index ~= v8.effect_index then
					v8.effect_index = effect_index
					v8.frame_position = 1
					v8.frame_timer = 0
				end

				if v8.last_speed_value ~= last_speed_value then
					v8.last_speed_value = last_speed_value

					if last_speed_value > 0 then
						v8.frames_per_second = last_speed_value / 128 * config.normal_frames_per_second * (effect.speed_multiplier or 1)
					else
						v8.frames_per_second = 0
					end
				end

				if v8.frames_per_second > 0 and #v12 > 1 then
					v8.frame_timer += 1 / 60 * v8.frames_per_second

					local frame_timer = math.floor(v8.frame_timer)

					if frame_timer > 0 then
						v8.frame_timer -= frame_timer

						v8.frame_position = (v8.frame_position - 1 + frame_timer) % #v12 + 1
					end
				end

				local v13 = v12[v8.frame_position]
				local v14 = select_image(v8, v13.mapping, active_mode)

				update_color(v8, v14, v13, active_mode, last_red, last_green, last_blue)

				local last_dimmer = 1 - v10

				if v8.last_dimmer ~= last_dimmer then
					set_property(v14, "ImageTransparency", last_dimmer) -- inferred equivalent call
					v8.last_dimmer = last_dimmer
				end

				if v8.last_strobe_value ~= last_strobe_value then
					v8.last_strobe_value = last_strobe_value

					if last_strobe_value > 0 then
						v8.half_interval = 0.5 / ((last_strobe_value - 1) / 254 * 14 + 1)
					else
						v8.half_interval = 0
						v8.strobe_timer = 0
						v8.strobe_on = true
					end
				end

				local v15

				if last_strobe_value > 0 then
					v8.strobe_timer += 1 / 60

					while v8.strobe_timer >= v8.half_interval do
						v8.strobe_timer -= v8.half_interval
						v8.strobe_on = not v8.strobe_on
					end

					v15 = v8.strobe_on
				else
					v15 = true
				end

				set_property(v14, "Visible", v15) -- inferred equivalent call
				set_property(v8.surface_gui, "Enabled", true) -- inferred equivalent call
			end
		end
	else
		if v8.is_on then
			set_off(v8) -- inferred equivalent call
		end

		v8.is_on = false
	end
end

